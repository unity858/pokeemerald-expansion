#!/usr/bin/env python3
"""
Re-add the FRLG (Kanto/Sevii) trainers that stay in one place to the Kanto maps
linked into the Emerald build.

Usage (from the repo root, after dev_scripts/kanto/convert_kanto_maps.py and
after a build, so src/data/trainers_frlg.h exists):
    python3 dev_scripts/kanto/add_kanto_trainers.py <orig_maps_dir> [--report out.json]

<orig_maps_dir> is the same pristine data/maps copy the converter takes
(e.g. `git archive my-hack data/maps | tar -x -C /tmp/orig`, then pass
/tmp/orig/data/maps).  The script is idempotent: re-running it replaces its
own output.

What it does:
  * picks every FRLG trainer object (an object whose script starts a
    trainerbattle) that is always present, i.e. has no hide flag.  Objects with
    a hide flag are Team Rocket / Silph Co. / Giovanni story actors and are
    skipped (FLAG_HIDE_MISC_KANTO_ROCKETS, FLAG_HIDE_SILPH_ROCKETS, ...), except
    Giovanni in the Viridian Gym, who is kept as the 8th Gym Leader.
  * adds the Elite Four and the Champion (Blastoise team,
    TRAINER_CHAMPION_FIRST_SQUIRTLE) as plain talk-to trainers.  None of the
    League sequence (doors, consecutive run, Hall of Fame) is kept.
  * gives each FRLG trainer a new Emerald trainer ID TRAINER_KANTO_<frlg name>
    (include/constants/opponents_kanto.h) and a party in
    src/data/trainers_kanto.party copied from src/data/trainers_frlg.party with
    a `Tera Type: <first type>` line on every Pokemon (same convention as
    src/data/trainers.party).
  * writes the trainer objects (FRLG position, movement type, sight range) into
    data/maps/*_Frlg/map.json and a plain battle script plus the FRLG intro /
    defeat / post-battle texts at the end of the map's scripts.inc.
    Gym Leaders give no badge, no TM and set no flag; badge lines are cut from
    their defeat texts.  Rematches are not kept.
"""

import collections
import json
import os
import re
import subprocess
import sys

ROOT = os.getcwd()
MAPS_DIR = os.path.join(ROOT, 'data', 'maps')
FRLG_SCRIPTS = os.path.join(ROOT, 'data', 'scripts', 'trainers_frlg.inc')
FRLG_TEXTS = os.path.join(ROOT, 'data', 'text', 'trainers_frlg.inc')
FRLG_PARTY = os.path.join(ROOT, 'src', 'data', 'trainers_frlg.party')
FRLG_PARTY_H = os.path.join(ROOT, 'src', 'data', 'trainers_frlg.h')
OUT_PARTY = os.path.join(ROOT, 'src', 'data', 'trainers_kanto.party')
OUT_CONSTANTS = os.path.join(ROOT, 'include', 'constants', 'opponents_kanto.h')

# First Kanto trainer ID: right after the last Emerald trainer (TRAINER_MAY_PLACEHOLDER = 854).
# IDs below TRAINER_FLAGS_COUNT (864) use the spare SaveBlock1 trainer flags, the rest
# use gSaveBlock3Ptr->kantoTrainerFlags.
KANTO_TRAINERS_START = 855

MARKER = '@ ---- Kanto trainers: generated by dev_scripts/kanto/add_kanto_trainers.py ----'
SCRIPT_TAG = '_EventScript_KT_'

# Hide flags that do not make a trainer a story actor.
ALLOWED_HIDE_FLAGS = {'FLAG_HIDE_VIRIDIAN_GIOVANNI'}

# League trainers: map -> (frlg trainer, intro, defeat, post, object script in pristine map
# or None to match the object by graphics).  They battle in a called sub-script in FRLG.
LEAGUE = {
    'PokemonLeague_LoreleisRoom_Frlg': ('TRAINER_ELITE_FOUR_LORELEI', 'PokemonLeague_LoreleisRoom_Text_Intro',
                                        'PokemonLeague_LoreleisRoom_Text_Defeat', 'PokemonLeague_LoreleisRoom_Text_PostBattle',
                                        'OBJ_EVENT_GFX_LORELEI', 'Lorelei'),
    'PokemonLeague_BrunosRoom_Frlg': ('TRAINER_ELITE_FOUR_BRUNO', 'PokemonLeague_BrunosRoom_Text_Intro',
                                      'PokemonLeague_BrunosRoom_Text_Defeat', 'PokemonLeague_BrunosRoom_Text_PostBattle',
                                      'OBJ_EVENT_GFX_BRUNO', 'Bruno'),
    'PokemonLeague_AgathasRoom_Frlg': ('TRAINER_ELITE_FOUR_AGATHA', 'PokemonLeague_AgathasRoom_Text_Intro',
                                       'PokemonLeague_AgathasRoom_Text_Defeat', 'PokemonLeague_AgathasRoom_Text_PostBattle',
                                       'OBJ_EVENT_GFX_AGATHA', 'Agatha'),
    'PokemonLeague_LancesRoom_Frlg': ('TRAINER_ELITE_FOUR_LANCE', 'PokemonLeague_LancesRoom_Text_Intro',
                                      'PokemonLeague_LancesRoom_Text_Defeat', 'PokemonLeague_LancesRoom_Text_PostBattle',
                                      'OBJ_EVENT_GFX_LANCE', 'Lance'),
    # FRLG has one Champion party per starter; the user picked the Blastoise one.
    'PokemonLeague_ChampionsRoom_Frlg': ('TRAINER_CHAMPION_FIRST_SQUIRTLE', 'PokemonLeague_ChampionsRoom_Text_Intro',
                                         'PokemonLeague_ChampionsRoom_Text_Defeat', 'PokemonLeague_ChampionsRoom_Text_PostBattle',
                                         'OBJ_EVENT_GFX_BLUE', 'Champion'),
}
# The FRLG Champion's name is the player-chosen rival name ({RIVAL}); Emerald's {RIVAL} is May/Brendan.
CHAMPION_NAME = 'BLUE'

LEADER_CLASSES = {'Leader Frlg'}
LEAGUE_CLASSES = {'Elite Four Frlg', 'Champion Frlg'}

LABEL_RE = re.compile(r'^([A-Za-z_]\w*)::?')


def parse_blocks(path):
    """label -> list of body lines (up to the next label)."""
    blocks = collections.OrderedDict()
    cur = None
    if not os.path.exists(path):
        return blocks
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        m = LABEL_RE.match(line)
        if m and not line[0].isspace():
            cur = m.group(1)
            blocks[cur] = []
            continue
        if cur is not None:
            blocks[cur].append(line)
    return blocks


def split_cmd(line):
    s = line.split('@', 1)[0].strip()
    if not s:
        return None, []
    parts = s.split(None, 1)
    args = [a.strip() for a in parts[1].split(',')] if len(parts) > 1 else []
    return parts[0], args


def text_body(blocks, label):
    lines = blocks.get(label)
    if lines is None:
        return None
    body = []
    for l in lines:
        c, _ = split_cmd(l)
        if c is None:
            continue
        if c != '.string':
            break
        body.append(l)
    return body or None


def string_content(lines):
    out = ''
    for l in lines:
        m = re.match(r'\s*\.string\s+"(.*)"\s*$', l)
        out += m.group(1)
    return out


def string_lines(content):
    """Re-split a string on \\n, \\l, \\p into .string lines (FRLG style)."""
    out = []
    cur = ''
    i = 0
    while i < len(content):
        if content[i] == '\\' and i + 1 < len(content) and content[i + 1] in 'nlp':
            cur += content[i:i + 2]
            out.append(cur)
            cur = ''
            i += 2
            continue
        cur += content[i]
        i += 1
    if cur:
        out.append(cur)
    return ['\t.string "%s"' % s for s in out]


def strip_badge_paragraphs(lines):
    """Cut a Gym Leader's defeat text before the first paragraph that hands over a badge."""
    content = string_content(lines)
    assert content.endswith('$')
    paras = content[:-1].split('\\p')
    keep = []
    for p in paras:
        if 'BADGE' in p or 'As proof of your victory' in p or 'proof of your' in p:
            break
        keep.append(p)
    if not keep:
        keep = paras[:1]
    return string_lines('\\p'.join(keep) + '$')


def parse_party(path):
    """trainer constant -> list of lines (header line included)."""
    out = collections.OrderedDict()
    cur = None
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        m = re.match(r'^=== (TRAINER_\w+) ===$', line)
        if m:
            cur = m.group(1)
            out[cur] = [line]
            continue
        if cur:
            out[cur].append(line)
    for k in out:
        while out[k] and out[k][-1].strip() == '':
            out[k].pop()
    return out


def parse_party_species(path):
    """trainer constant -> species constants in party order, from the generated trainers_frlg.h."""
    out = {}
    cur = None
    for line in open(path, encoding='utf-8'):
        m = re.match(r'^\s*\[DIFFICULTY_NORMAL\]\[(TRAINER_\w+)\]\s*=', line)
        if m:
            cur = m.group(1)
            out[cur] = []
            continue
        m = re.match(r'^\s*\.species = (SPECIES_\w+),', line)
        if m and cur:
            out[cur].append(m.group(1))
    return out


def species_first_types():
    cmd = ['arm-none-eabi-cpp', '-iquote', 'include', '-Wno-trigraphs', '-DMODERN=1', '-DTESTING=0',
           '-DEMERALD', '-std=gnu17', 'src/pokemon.c']
    pre = subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout
    types = {}
    cur = None
    for line in pre.split('\n'):
        m = re.match(r'^\s*\[(SPECIES_\w+)\]\s*=\s*$', line) or re.match(r'^\s*\[(SPECIES_\w+)\]\s*=\s*\{', line)
        if m:
            cur = m.group(1)
            continue
        m = re.match(r'^\s*\.types = \{ (TYPE_\w+),', line)
        if m and cur and cur not in types:
            types[cur] = m.group(1)
    return types


def type_name(t):
    return t[len('TYPE_'):].capitalize()


def find_battle(blocks, label, depth=0):
    """First trainerbattle command reached from label (fallthrough and calls), plus the
    first msgbox after it in the same block (the post-battle text)."""
    lines = blocks.get(label)
    if lines is None or depth > 4:
        return None
    for i, l in enumerate(lines):
        c, a = split_cmd(l)
        if c is None:
            continue
        if c.startswith('trainerbattle'):
            post = None
            for l2 in lines[i + 1:]:
                c2, a2 = split_cmd(l2)
                if c2 == 'msgbox':
                    post = a2[0]
                    break
                if c2 in ('end', 'goto', 'return', 'release', 'releaseall'):
                    break
            return c, a, post
        if c in ('end', 'return'):
            return None
        if c == 'goto':
            return find_battle(blocks, a[0], depth + 1)
    return None


def camel_from_label(label):
    return label.split('_EventScript_', 1)[1] if '_EventScript_' in label else label


def main():
    orig = sys.argv[1]
    report_path = sys.argv[sys.argv.index('--report') + 1] if '--report' in sys.argv else None

    inc_blocks = parse_blocks(FRLG_SCRIPTS)
    inc_text_blocks = parse_blocks(FRLG_TEXTS)
    party = parse_party(FRLG_PARTY)
    party_species = parse_party_species(FRLG_PARTY_H)
    first_type = species_first_types()

    # Labels that already exist in the converted Kanto scripts (outside our generated section).
    names = sorted(d for d in os.listdir(orig) if d.endswith('_Frlg'))
    converted = {}
    existing_labels = set()
    for name in names:
        p = os.path.join(MAPS_DIR, name, 'scripts.inc')
        txt = open(p, encoding='utf-8').read() if os.path.exists(p) else ''
        if MARKER in txt:
            txt = txt[:txt.index(MARKER)].rstrip('\n') + '\n'
        converted[name] = txt
        for l in txt.split('\n'):
            m = LABEL_RE.match(l)
            if m:
                existing_labels.add(m.group(1))

    # FRLG texts can live in another map's scripts.inc (e.g. Route 21 North texts in Route 21 South)
    all_map_blocks = collections.OrderedDict()
    for name in names:
        all_map_blocks.update(parse_blocks(os.path.join(orig, name, 'scripts.inc')))

    report = {'added': [], 'skipped': [], 'trainers': {}}
    trainer_order = []          # frlg trainer constants in ID order
    trainer_info = {}           # frlg const -> dict(kind, maps)
    per_map = collections.defaultdict(list)   # map -> list of (obj, script_text)
    emitted_texts = set()

    def need_text(name, label, src_blocks, out):
        """Copy a FRLG text into this map's output unless it already exists somewhere."""
        if label in existing_labels or label in emitted_texts:
            return
        body = None
        for b in src_blocks:
            body = text_body(b, label)
            if body:
                break
        if body is None:
            raise SystemExit('%s: text %s not found' % (name, label))
        emitted_texts.add(label)
        out.append('%s::\n%s\n' % (label, '\n'.join(body)))

    for name in names:
        base = name[:-len('_Frlg')]
        m = json.load(open(os.path.join(orig, name, 'map.json'), encoding='utf-8'))
        map_blocks = parse_blocks(os.path.join(orig, name, 'scripts.inc'))
        srcs = [map_blocks, all_map_blocks, inc_blocks, inc_text_blocks]
        for o in m.get('object_events') or []:
            if o.get('type') == 'clone':
                continue
            script = o.get('script', '0x0')
            league = LEAGUE.get(name)
            if league and o.get('graphics_id') == league[4]:
                tconst, intro, defeat, post = league[:4]
                cmd, args = 'trainerbattle_single', [tconst, intro, defeat]
                label_suffix = league[5]
            else:
                blocks = map_blocks if script in map_blocks else inc_blocks
                res = find_battle(blocks, script)
                if res is None:
                    continue
                cmd, args, post = res
                tconst = args[0]
                label_suffix = camel_from_label(script)
                flag = o.get('flag', '0')
                if flag not in ('0', '') and flag not in ALLOWED_HIDE_FLAGS:
                    report['skipped'].append((base, tconst, 'hide flag ' + flag))
                    continue
                if cmd not in ('trainerbattle_single', 'trainerbattle_double'):
                    report['skipped'].append((base, tconst, cmd))
                    continue
            if tconst not in party:
                raise SystemExit('%s: no FRLG party for %s' % (name, tconst))
            cls = next((l.split(':', 1)[1].strip() for l in party[tconst] if l.startswith('Class:')), '')
            is_leader = cls in LEADER_CLASSES
            new_const = 'TRAINER_KANTO_' + tconst[len('TRAINER_'):]
            if tconst not in trainer_info:
                trainer_info[tconst] = {'const': new_const, 'class': cls, 'maps': []}
                trainer_order.append(tconst)
            trainer_info[tconst]['maps'].append(base)

            out = []
            intro, defeat = args[1], args[2]
            label = '%s%s%s' % (base, SCRIPT_TAG, label_suffix)
            # Texts
            need_text(name, intro, srcs, out)
            if is_leader:
                # Badge hand-over cut from the defeat text.
                body = None
                for b in srcs:
                    body = text_body(b, defeat)
                    if body:
                        break
                body = strip_badge_paragraphs(body)
                new_defeat = defeat.replace('_Text_', '_Text_KT_')
                out.append('%s::\n%s\n' % (new_defeat, '\n'.join(body)))
                defeat = new_defeat
                if post is None or 'TM' in post or 'Badge' in post:
                    # No post-battle text that doesn't talk about the badge/TM: repeat the defeat text.
                    cand = defeat.replace('_Text_KT_', '_Text_').replace('Defeat', 'PostBattle')
                    post = cand if any(text_body(b, cand) for b in srcs) else new_defeat
                if post != new_defeat:
                    need_text(name, post, srcs, out)
            else:
                need_text(name, defeat, srcs, out)
                if post:
                    need_text(name, post, srcs, out)
            if cmd == 'trainerbattle_double':
                need_text(name, args[3], srcs, out)

            if tconst.startswith('TRAINER_CHAMPION'):
                out = [x.replace('{RIVAL}', CHAMPION_NAME) for x in out]

            intro_has_bgm = any('PLAY_BGM' in l for b in srcs for l in (text_body(b, intro) or []))
            music = ', NULL, NO_MUSIC' if intro_has_bgm else ''
            s = ['%s::' % label]
            if cmd == 'trainerbattle_double':
                s.append('\ttrainerbattle_double %s, %s, %s, %s%s' % (new_const, intro, defeat, args[3], music))
            else:
                s.append('\ttrainerbattle_single %s, %s, %s%s' % (new_const, intro, defeat, music))
            if post:
                s.append('\tmsgbox %s, MSGBOX_AUTOCLOSE' % post)
            s.append('\tend')
            script_text = '\n'.join(s) + '\n\n' + '\n'.join(out)

            obj = collections.OrderedDict()
            for k in ('type', 'local_id', 'graphics_id', 'x', 'y', 'elevation', 'movement_type', 'movement_range_x',
                      'movement_range_y', 'trainer_type', 'trainer_sight_or_berry_tree_id', 'script', 'flag'):
                if k in o:
                    obj[k] = o[k]
            obj['script'] = label
            obj['flag'] = '0'
            per_map[name].append((obj, script_text))
            report['added'].append((base, tconst, new_const, label, o['movement_type'], o.get('trainer_type'),
                                    o.get('trainer_sight_or_berry_tree_id')))

    # ---- maps ----
    for name in names:
        path = os.path.join(MAPS_DIR, name, 'map.json')
        mj = json.load(open(path, encoding='utf-8'), object_pairs_hook=collections.OrderedDict)
        objs = mj['object_events']
        new_objs = per_map.get(name, [])
        wanted = {(o['x'], o['y'], o['graphics_id']) for o, _ in new_objs}
        # drop stale generated objects
        objs = [o for o in objs if SCRIPT_TAG not in o.get('script', '') or (o['x'], o['y'], o['graphics_id']) in wanted]
        for no, _ in new_objs:
            hit = None
            for i, o in enumerate(objs):
                if o.get('type') != 'clone' and (o['x'], o['y'], o['graphics_id']) == (no['x'], no['y'], no['graphics_id']):
                    hit = i
                    break
            if hit is not None:
                # e.g. the Elite Four, kept by the converter as talkers: turn them into trainers
                old = objs[hit]
                if 'local_id' in old and 'local_id' not in no:
                    no = collections.OrderedDict([('local_id', old['local_id'])] + list(no.items()))
                objs[hit] = no
            else:
                objs.append(no)
        if objs != mj['object_events']:
            mj['object_events'] = objs
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(mj, f, indent=2, ensure_ascii=False)
                f.write('\n')
        txt = converted[name]
        if new_objs:
            txt = txt.rstrip('\n') + '\n\n' + MARKER + '\n\n' + '\n'.join(s for _, s in new_objs).rstrip('\n') + '\n'
        sp = os.path.join(MAPS_DIR, name, 'scripts.inc')
        if os.path.exists(sp) and open(sp, encoding='utf-8').read() != txt:
            with open(sp, 'w', encoding='utf-8') as f:
                f.write(txt)

    # ---- constants ----
    with open(OUT_CONSTANTS, 'w') as f:
        f.write('// DO NOT MODIFY THIS FILE! It is generated by dev_scripts/kanto/add_kanto_trainers.py\n')
        f.write('#ifndef GUARD_CONSTANTS_OPPONENTS_KANTO_H\n#define GUARD_CONSTANTS_OPPONENTS_KANTO_H\n\n')
        f.write('// FRLG trainers placed on the Kanto/Sevii maps of the Emerald build.\n')
        f.write('// Their parties are in src/data/trainers_kanto.party.\n\n')
        f.write('#define KANTO_TRAINERS_START %d\n\n' % KANTO_TRAINERS_START)
        for i, t in enumerate(trainer_order):
            f.write('#define %-48s %d // %s\n' % (trainer_info[t]['const'], KANTO_TRAINERS_START + i, t))
        f.write('\n#define KANTO_TRAINERS_COUNT %d\n' % len(trainer_order))
        f.write('#define KANTO_TRAINERS_END   (KANTO_TRAINERS_START + KANTO_TRAINERS_COUNT)\n')
        f.write('\n#endif // GUARD_CONSTANTS_OPPONENTS_KANTO_H\n')

    # ---- parties ----
    out = ['/*',
           'DO NOT MODIFY THIS FILE BY HAND! It is generated by dev_scripts/kanto/add_kanto_trainers.py',
           'from src/data/trainers_frlg.party (FRLG party, class, name and pic).',
           'Every Pokemon gets "Tera Type: <its first type>" like src/data/trainers.party.',
           'Levels are rescaled at battle time by src/level_scaling.c.',
           '*/', '']
    for t in trainer_order:
        lines = list(party[t])
        lines[0] = '=== %s ===' % trainer_info[t]['const']
        species = party_species[t]
        res = []
        mon = -1
        in_mon = False
        for i, l in enumerate(lines):
            if t.startswith('TRAINER_CHAMPION') and l.startswith('Name:'):
                l = 'Name: ' + CHAMPION_NAME
            if l.startswith('Tera Type:'):
                continue
            res.append(l)
            if l.strip() == '':
                in_mon = False
                continue
            if i > 0 and not in_mon and ':' not in l and not l.startswith('- ') and res[-2].strip() == '':
                in_mon = True
                mon += 1
            if in_mon and l.startswith('Level:'):
                res.append('Tera Type: ' + type_name(first_type[species[mon]]))
        assert mon + 1 == len(species), (t, mon, species)
        out.extend(res)
        out.append('')
    with open(OUT_PARTY, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))

    report['trainers'] = {trainer_info[t]['const']: trainer_info[t] for t in trainer_order}
    counts = collections.Counter()
    for t in trainer_order:
        counts[trainer_info[t]['class']] += 1
    print('trainer IDs: %d (%d..%d), objects: %d, skipped objects: %d' % (
        len(trainer_order), KANTO_TRAINERS_START, KANTO_TRAINERS_START + len(trainer_order) - 1,
        len(report['added']), len(report['skipped'])))
    if report_path:
        json.dump(report, open(report_path, 'w'), indent=1)


if __name__ == '__main__':
    main()
